const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const X = require('xlsx');
(async () => {
 const browser = await chromium.launch({headless:true, executablePath:process.env.BROWSER_EXECUTABLE});
 try {
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:3001';
  await page.addInitScript(() => localStorage.setItem('gradezy_students_20_v1', 'true'));
  await page.goto(base+'/students');
  await page.getByRole('heading',{name:'Students',exact:true}).waitFor();
  assert.deepEqual(await page.locator('thead th').allTextContents(), ['NCG ID','ESL ID','First Name','Last Name','Campus','Group Code','Program Name','ESL Email','Student Status']);
  await page.getByRole('button',{name:'Import students from Excel',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Import students',exact:true});
  await dialog.waitFor();
  const book=X.utils.book_new();
  X.utils.book_append_sheet(book,X.utils.aoa_to_sheet([['NCG ID','ESL ID','First Name','Last Name','Campus','Group Code','Program Name','ESL Email','Student Status'],['2341452','129685','Ailton','Dos Reis Quaresma','Birmingham - York House','C4L5S2','FdSc Computing','2502-129685@esl.ac.uk','Active']]),'Students');
  await dialog.getByLabel('Upload tracker workbook').setInputFiles({name:'students.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:X.write(book,{type:'buffer',bookType:'xlsx'})});
  await dialog.getByRole('button',{name:'Confirm tracker import',exact:true}).click();
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.getByLabel('Directory cohort').selectOption('cohort-4');
  assert.deepEqual(await page.locator('tbody tr td').allTextContents(), ['2341452','129685','Ailton','Dos Reis Quaresma','Birmingham - York House','C4L5S2','FdSc Computing','2502-129685@esl.ac.uk','Active']);
  await page.getByRole('button',{name:'View student Ailton Dos Reis Quaresma',exact:true}).click();
  const profile=page.getByRole('dialog',{name:'Ailton Dos Reis Quaresma',exact:true});
  await profile.getByRole('cell',{name:/^CMP211/}).waitFor();
  const courseRows=profile.locator('table').first().locator('tbody tr');
  assert.equal(await courseRows.count(),6);
  assert.ok((await courseRows.allTextContents()).every(text=>text.includes('Cohort 4')&&text.includes('Computing')));
  await profile.getByLabel('Group Code', {exact:true}).fill('C2L5S2');
  await profile.getByRole('button', {name:'Save student details',exact:true}).click();
  await profile.getByRole('alert').filter({hasText:'must match'}).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.getByRole('button',{name:'Add student',exact:true}).click();
  const add=page.getByRole('dialog',{name:'Add student',exact:true});
  await add.getByLabel('Student / NCG ID',{exact:true}).fill('MANUAL1');
  await add.getByLabel('First name',{exact:true}).fill('Manual');
  await add.getByLabel('Last name',{exact:true}).fill('Student');
  await add.getByLabel('Group Code',{exact:true}).fill('C4L5S2');
  await add.getByLabel('Program Name',{exact:true}).fill('FdSc Computing');
  await add.getByRole('button',{name:'Add enrolment',exact:true}).click();
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.getByRole('cell',{name:'MANUAL1',exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'View student Ailton Dos Reis Quaresma',exact:true}).click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  console.log('Student modal checks passed: exact columns, group-derived cohorts, profile modules, manual entry, modal close and mobile layout.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
