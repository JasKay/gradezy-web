const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const X = require('xlsx');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE });
  try {
    const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 1000 } });
    await context.addInitScript(() => localStorage.setItem("gradezy_practice_opt_out", "true"));
    await context.addInitScript(() => localStorage.setItem("gradezy_students_20_v1", "true"));
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3001';
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('gradezy_workflow_v1')));
    const workbook = rows => {
      const book = X.utils.book_new();
      X.utils.book_append_sheet(book, X.utils.aoa_to_sheet(rows), 'Tracker');
      return X.write(book, { type: 'buffer', bookType: 'xlsx' });
    };
    const upload = async (summary, rows) => {
      if (summary === 'Import students from Excel') await page.getByRole('button', { name: summary, exact: true }).click();
      else await page.getByText(summary, { exact: true }).click();
      await page.getByLabel('Upload tracker workbook').setInputFiles({ name: 'tracker.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: workbook(rows) });
      await page.getByRole('button', { name: 'Confirm tracker import', exact: true }).click();
    };
    await page.goto(base + '/students');
    await page.getByRole('heading', { name: 'Students', exact: true }).waitFor();
    assert.equal(await page.getByText(/Dummy|Sample workspace|Start with the people|Enrolled students/).count(), 0);
    assert.equal(await page.getByRole('link', { name: 'Upload preparation', exact: true }).count(), 0);
    await upload('Import students from Excel', [['NCG ID', 'First Name', 'Last Name', 'Cohort', 'Program Name'], ['001', 'Alex', 'Taylor', 'Cohort 1', 'Business'], ['002', 'Sam', 'Lee', 'Cohort 2', 'Computing']]);
    let w = await saved();
    assert.equal(w.students.length, 2);
    const pending = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download list', exact: true }).click();
    const file = await pending;
    const book = X.readFile(await file.path());
    assert.deepEqual(book.SheetNames, ['Students']);
    const rows = X.utils.sheet_to_json(book.Sheets.Students, { header: 1 });
    assert.equal(rows.length, 2);
    assert.equal(rows[1][0], '001');
    await upload('Import students from Excel', [['NCG ID', 'First Name', 'Last Name', 'Cohort', 'Program Name'], ['001', 'Alex', 'Taylor', 'Cohort 3', 'Health and Social Care']]);
    await page.getByLabel('Directory cohort').selectOption('');
    assert.equal(await page.locator('tbody tr').count(), 3);
    assert.equal(await page.getByRole('cell', { name: '001', exact: true }).count(), 2);
    for (let i = 0; i < 3; i++) assert.equal((await page.locator('tbody tr').nth(i).locator('td').nth(5).innerText()).match(/Cohort/g).length, 1);
    const allDownload = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download list', exact: true }).click();
    const allBook = X.readFile(await (await allDownload).path());
    const allRows = X.utils.sheet_to_json(allBook.Sheets.Students, { header: 1 });
    assert.equal(allRows.length, 4);
    assert.ok(allRows.slice(1).every(row => !row.slice(-2).some(value => String(value).includes(';'))));
    await page.getByLabel('Directory programme').selectOption('Computer Science');
    await page.getByRole('cell', { name: '002', exact: true }).waitFor();
    assert.equal(await page.getByRole('cell', { name: '001', exact: true }).count(), 0);
    await page.goto(base + '/assessments');
    await page.getByRole('button', { name: 'Assessment schedule', exact: true }).click();
    await upload('Import assessment tracker from Excel', [['Cohort', 'Module Code', 'Assessment', 'Programme'], ['Cohort 1', 'BUS101', 'Report', 'Business'], ['Cohort 1', 'BUS101', 'Presentation', 'Business']]);
    await page.getByRole('link', { name: 'Report', exact: true }).waitFor();

    await page.goto(base + '/progress');
    await page.getByLabel('Tracker module').selectOption('BUS101');
    await page.getByLabel('Tracker cohort').selectOption('cohort-1');
    assert.equal(await page.locator('tbody tr').count(), 1);
    await page.getByRole('button', {name:'Alex Taylor',exact:true}).click();
    await page.getByLabel('Progress 1 -W4', { exact: true }).fill('On track');
    await page.getByRole('button', { name: 'Save progress', exact: true }).click();
    await page.getByRole('button',{name:'Import Excel',exact:true}).click();
    await page.getByLabel('Upload progress workbook').setInputFiles({name:'progress.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:workbook([['NCG ID','First Name','Last Name','Progress 2-W8'],['001','Alex','Taylor','Complete']])});
    await page.getByRole('button',{name:'Confirm progress import',exact:true}).click();
    await page.getByRole('cell',{name:'Complete',exact:true}).waitFor();
    assert.equal((await saved()).moduleProgress[0].values.progress1,'On track');
    await page.getByRole('button',{name:'Marking & Allocation',exact:true}).click();
    await page.getByRole('button',{name:'Import Excel',exact:true}).click();
    await page.getByLabel('Upload tracker workbook').setInputFiles({ name: 'marking.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: workbook([['NCG ID', 'First Name', 'Last Name', '1st Marker', 'Grade (out of 100%)'], ['001', 'Alex', 'Taylor', 'Jordan Smith', '0']]) });
    await page.getByRole('button', { name: 'Confirm tracker import', exact: true }).click();
    await page.getByRole('cell', { name: 'Jordan Smith', exact: true }).waitFor();
    await page.getByText('Jordan Smith: 1 allocated - 1 marked',{exact:true}).waitFor();
    assert.equal(await page.getByLabel('Tracker module').inputValue(), 'BUS101');
    await page.goto(base + '/dashboard');
    await page.getByRole('heading', { name: 'Ask Gradezy', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Ask assistant', exact: false }).click();
    await page.getByText('Workspace search', { exact: true }).waitFor();
    await page.goto(base + '/sources');
    await page.getByRole('heading', { name: 'Integrations', exact: true }).first().waitFor();
    assert.equal(await page.getByText('Planned', { exact: true }).count(), 3);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base + '/progress');
    await page.getByLabel('Tracker module').waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('Tracker browser checks passed: Excel imports, filtered download, checkpoints, zero-grade marking count, module link, Overview assistant, integrations and mobile layout.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
