const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3001';
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('gradezy_workflow_v1')));
    await page.goto(base + '/dashboard');
    await page.getByRole('heading', { name: 'Ask Gradezy', exact: true }).waitFor();
    let w = await saved();
    assert.equal(w.students.length, 36);
    assert.equal(w.assessments.length, 18);
    assert.equal(w.imports.length, 4);
    const ask = async question => {
      await page.getByLabel('Your question', { exact: true }).fill(question);
      await page.getByRole('button', { name: 'Ask assistant', exact: false }).click();
      await page.getByRole('button', { name: 'Close assistant answer', exact: true }).waitFor();
      return page.locator('.wf-answer').innerText();
    };
    let answer = await ask("Who hasn't submitted BUS101 in Cohort 1?");
    assert.ok(answer.includes('outstanding submissions.'));
    assert.ok(answer.includes('BUS101'));
    assert.ok(!answer.includes('COM102'));
    assert.ok(await page.locator('.wf-answer-links a').count() > 0);
    await page.getByRole('button', { name: 'Close assistant answer', exact: true }).click();
    assert.equal(await page.locator('.wf-answer').count(), 0);
    answer = await ask('Which students in Cohort 1 need support?');
    assert.ok(answer.includes('students need a progress follow-up.'));
    assert.ok(!answer.includes('Week 8 On track'));
    answer = await ask('How much work is allocated to Rachel Adams?');
    assert.ok(answer.includes('Rachel Adams:'));
    assert.ok(!answer.includes('Daniel Brooks:'));
    answer = await ask('What is overdue in BUS999?');
    assert.ok(answer.includes("couldn't find"));
    await page.reload();
    await page.getByRole('heading', { name: 'Ask Gradezy', exact: true }).waitFor();
    assert.equal((await saved()).students.length, 36);
    await page.goto(base + '/students');
    await page.getByRole('heading', { name: 'Students', exact: true }).waitFor();
    await page.getByText('Add student', { exact: true }).click();
    await page.getByLabel('Student / NCG ID', { exact: true }).fill('OWN001');
    await page.getByLabel('First name', { exact: true }).fill('Own');
    await page.getByLabel('Last name', { exact: true }).fill('Record');
    await page.getByRole('button', { name: 'Add enrolment', exact: true }).click();
    await page.getByRole('cell', { name: 'OWN001', exact: true }).waitFor();
    await page.goto(base + '/settings');
    await page.getByRole('button', { name: 'Remove practice records', exact: true }).click();
    assert.equal((await saved()).students.length, 1);
    await page.goto(base + '/dashboard');
    await page.getByRole('heading', { name: 'Ask Gradezy', exact: true }).waitFor();
    assert.equal((await saved()).students.length, 1);
    await page.goto(base + '/settings');
    await page.getByRole('button', { name: 'Load practice records', exact: true }).click();
    assert.equal((await saved()).students.length, 37);
    await page.getByRole('button', { name: 'Load practice records', exact: true }).click();
    assert.equal((await saved()).students.length, 37);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base + '/dashboard');
    await page.getByRole('heading', { name: 'Ask Gradezy', exact: true }).waitFor();
    await ask('Who is awaiting marking in BUS101?');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.getByRole('button', { name: 'Close assistant answer', exact: true }).click();
    assert.deepEqual(errors, []);
    console.log('Practice browser checks passed: auto-population, scoped search, source links, close/reopen, persistence, safe removal/reload and mobile.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
