const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await context.addInitScript(() => localStorage.setItem('gradezy_practice_opt_out', 'true'));
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3001';
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('gradezy_workflow_v1')));
    await page.goto(base + '/assessments');
    await page.getByRole('heading', { name: 'NCG modules', exact: true }).waitFor();
    assert.equal(await page.locator('tbody tr').count(), 45);
    await page.getByLabel('Filter NCG programme').selectOption('COMP');
    assert.equal(await page.locator('tbody tr').count(), 18);
    assert.equal(await page.getByRole('cell', { name: 'BM101', exact: true }).count(), 0);
    await page.getByLabel('Search NCG modules').fill('Dynamic Website');
    assert.equal(await page.locator('tbody tr').count(), 1);
    await page.getByRole('cell', { name: 'CMP114', exact: true }).waitFor();
    await page.getByLabel('Search NCG modules').fill('ACS100');
    await page.getByRole('link', { name: 'Add assessment', exact: false }).click();
    await page.getByLabel('Module code', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Module code', { exact: true }).inputValue(), 'ACS100');
    assert.equal(await page.getByLabel('Module name', { exact: true }).inputValue(), 'Academic Study Skills');
    assert.equal(await page.getByLabel('Programme', { exact: true }).inputValue(), 'Computer Science');
    assert.ok(await page.getByLabel('Programme', { exact: true }).innerText().then(t => t.includes('Computing')));
    await page.getByLabel('Assessment name', { exact: true }).fill('Study skills assignment');
    await page.getByRole('button', { name: 'Create assessment', exact: true }).click();
    await page.waitForURL('**/workflow/**');
    await page.getByRole('heading', { name: 'Study skills assignment', exact: true }).waitFor();
    assert.equal((await saved()).assessments[0].subject, 'Computer Science');
    await page.goto(base + '/assessments');
    await page.getByLabel('Filter NCG programme').selectOption('BM');
    await page.getByLabel('Search NCG modules').fill('ACS100');
    await page.getByRole('link', { name: 'Add assessment', exact: false }).click();
    await page.getByLabel('Module code', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Programme', { exact: true }).inputValue(), 'Business Management');
    await page.getByLabel('Assessment name', { exact: true }).fill('Study skills assignment');
    await page.getByRole('button', { name: 'Create assessment', exact: true }).click();
    await page.waitForURL('**/workflow/**');
    await page.getByRole('heading', { name: 'Study skills assignment', exact: true }).waitFor();
    assert.equal((await saved()).assessments.length, 2);
    await page.goto(base + '/assessments');
    await page.getByLabel('Search NCG modules').fill('ACS100');
    assert.equal(await page.locator('tbody tr').count(), 1);
    await page.getByText('2 scheduled', { exact: true }).click();
    assert.equal(await page.locator('.wf-module-assessments a').count(), 2);
    await page.getByLabel('Filter NCG programme').selectOption('COMP');
    await page.getByText('1 scheduled', { exact: true }).waitFor();
    await page.getByLabel('Filter NCG programme').selectOption('HSC');
    await page.getByLabel('Search NCG modules').fill('IH201');
    await page.getByRole('cell', { name: 'Health Inequalities and Social Justice in the 21st Century', exact: true }).waitFor();
    assert.equal(await page.locator('tbody tr').count(), 1);
    await page.getByLabel('Search NCG modules').fill('IH202');
    await page.getByRole('cell', { name: 'The Individual Across the Life Course', exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
    await page.goto(base + '/dashboard');
    await page.getByLabel('Your question', { exact: true }).fill('What is BM101?');
    await page.getByRole('button', { name: 'Ask assistant', exact: false }).click();
    await page.getByRole('button', { name: 'Close assistant answer', exact: true }).waitFor();
    assert.ok((await page.locator('.wf-answer').innerText()).includes('The Business Environment'));
    assert.deepEqual(errors, []);
    console.log('NCG browser checks passed: 45 unique modules, programme filtering, module-name prefill, shared-module schedules, HSC course separation, mobile and catalogue search.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
