const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:3001';
    await page.addInitScript(() => localStorage.setItem('gradezy_students_20_v1', 'true'));
    await page.goto(base + '/assessments');
    await page.getByRole('heading', { name: 'NCG modules', exact: true }).waitFor();
    assert.equal(await page.locator('tbody tr').count(), 99);
    for (const [number, count] of [[1,16],[2,12],[3,18],[4,18],[5,21],[6,14]]) {
      await page.getByLabel('Filter NCG cohort').selectOption('cohort-' + number);
      assert.equal(await page.locator('tbody tr').count(), count);
      for (const value of await page.locator('tbody tr').evaluateAll(rows => rows.map(r => r.cells[3].textContent))) assert.equal(value, 'Cohort ' + number);
    }
    await page.getByLabel('Filter NCG cohort').selectOption('');
    await page.getByRole('button', { name: 'Sort cohorts descending', exact: true }).click();
    assert.equal(await page.locator('tbody tr').first().locator('td').nth(3).innerText(), 'Cohort 6');
    await page.getByRole('button', { name: 'Sort cohorts ascending', exact: true }).click();
    await page.getByLabel('Search NCG modules').fill('BM301');
    assert.equal(await page.locator('tbody tr').count(), 2);
    await page.getByRole('button', { name: 'Edit BM301 BM Cohort 1', exact: true }).click();
    await page.getByLabel('Edit module name').fill('Business Strategy - updated');
    await page.getByRole('button', { name: 'Save changes', exact: true }).click();
    assert.equal(await page.getByRole('cell', { name: 'Business Strategy', exact: true }).count(), 1);
    await page.reload(); await page.getByLabel('Search NCG modules').fill('BM301');
    await page.getByRole('cell', { name: 'Business Strategy - updated', exact: true }).waitFor();
    await page.getByLabel('Search NCG modules').fill('ACS100');
    assert.equal(await page.locator('tbody tr').count(), 5);
    assert.equal(await page.getByRole('link', { name: 'Add assessment', exact: false }).count(), 1);
    await page.getByRole('link', { name: 'Add assessment', exact: false }).click();
    await page.getByLabel('Module code', { exact: true }).fill('ACS100');
    await page.getByLabel('Programme', { exact: true }).selectOption('Computer Science');
    assert.equal(await page.getByLabel('Cohort', { exact: true }).inputValue(), '');
    await page.getByLabel('Cohort', { exact: true }).selectOption('cohort-5');
    await page.getByLabel('Assessment name', { exact: true }).fill('Study skills assignment');
    await page.getByRole('button', { name: 'Create assessment', exact: true }).click();
    await page.waitForURL('**/workflow/**');
    await page.goto(base + '/assessments');
    await page.getByLabel('Search NCG modules').fill('ACS100');
    assert.equal(await page.getByText('1 scheduled', { exact: true }).count(), 1);
    await page.getByText('1 scheduled', { exact: true }).click();
    assert.deepEqual(await page.locator('.wf-module-assessments a').allTextContents(), ['Study skills assignment']);
    await page.getByRole('button', { name: 'Assessment schedule', exact: true }).click();
    assert.equal(await page.locator('tbody tr').count(), 99);
    await page.getByLabel('Search assessments').fill('Study skills assignment');
    assert.equal(await page.locator('tbody tr').count(), 1);
    assert.equal(await page.locator('tbody tr td').nth(2).innerText(), 'Cohort 5');
    await page.goto(base + '/assessments/new');
    await page.getByLabel('Module code', { exact: true }).fill('IHS305');
    await page.getByLabel('Cohort', { exact: true }).selectOption('cohort-2');
    await page.getByLabel('Assessment name', { exact: true }).fill('Dissertation submission');
    await page.getByLabel('Semester', { exact: true }).selectOption('C2S6');
    await page.getByRole('button', { name: 'Create assessment', exact: true }).click();
    await page.waitForURL('**/workflow/**');
    await page.goto(base + '/assessments');
    await page.getByLabel('Search NCG modules').fill('IHS305');
    await page.getByLabel('Filter NCG cohort').selectOption('cohort-2');
    assert.equal(await page.locator('tbody tr').count(), 2);
    const semesterSix = page.locator('tbody tr').filter({ hasText: 'C2S6' });
    await semesterSix.getByText('1 scheduled', { exact: true }).click();
    await semesterSix.getByRole('link', { name: 'Dissertation submission', exact: true }).waitFor();
    assert.equal(await page.locator('tbody tr').filter({ hasText: 'C2S5' }).getByText('Not scheduled', { exact: true }).count(), 1);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('NCG browser checks passed: 99 supplied offerings, exact cohort counts, semester preservation, independent edits, sorting and scoped assessment links.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
